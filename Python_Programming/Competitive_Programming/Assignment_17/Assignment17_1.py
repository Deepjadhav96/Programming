# Create one module named Arithmetic which contains 4 functions:

# Add() for addition
# Sub() for subtraction
# Mult() for multiplication
# Div() for division

# All functions accept two parameters as input and perform the respective operation. Write a Python program that calls all these functions from the Arithmetic module by accepting the parameters from the user.

def Add(No1, No2):
    return No1 + No2
def Sub(No1, No2):
    return No1 - No2
def Mult(No1, No2):
    return No1 * No2
def Div(No1, No2):
    return No1 / No2
